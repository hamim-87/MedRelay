"""Collect measured results into reports/final_report.md (no number is typed in by hand)."""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
out = ROOT / "reports"
out.mkdir(exist_ok=True)


def csv(name):
    p = R / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def block(title, df, cols=None, note=None, round_=3):
    if df is None:
        return f"### {title}\n\n(not available)\n\n"
    d = df[cols] if cols else df
    return f"### {title}\n\n" + (f"{note}\n\n" if note else "") + "```\n" + d.round(round_).to_string(index=False) + "\n```\n\n"


hw = json.loads((R / "hardware.json").read_text()) if (R / "hardware.json").exists() else {}
mode = (R / "final_summary.csv").exists()
L = ["# MedRelay on IBM LinuxONE - measured results", "",
     f"Generated by `scripts/make_report.py` from `results/`. Executing host: **{hw.get('uname_m')}** ({hw.get('byteorder')}-endian), {hw.get('nproc')} CPUs, {hw.get('memory_total_gb')} GB RAM, hypervisor {hw.get('hypervisor')}, Python {hw.get('python')}.", "",
     "All follow-up outcomes are **simulated**; action labels are **weak (no human-reviewed gold)**; extraction is evaluated on a **developer-annotated** set and synthetic-by-construction documents. Nothing here is clinically validated.", ""]
L.append(block("Summary", csv("final_summary")))
L.append(block("Data validation", pd.DataFrame([{"check": k, "passed": v["ok"], "detail": str(v["detail"])[:100]} for k, v in json.loads((R / "data_validation.json").read_text())["checks"].items()]) if (R / "data_validation.json").exists() else None))
L.append(block("Experiment 1 - obligation extraction (350M model)", csv("exp1_extraction_primary"), ["extractor", "corpus", "n_docs", "typed_precision", "typed_recall", "typed_f1", "typed_f1_lo", "typed_f1_hi", "det_f1", "deadline_acc", "dep_f1_on_matched", "unsupported_field_rate", "schema_valid", "latency_mean_s", "latency_p95_s"]))
L.append(block("Experiment 1 - larger local model (smaller sample)", csv("exp1_extraction_large"), ["extractor", "model", "corpus", "n_docs", "typed_precision", "typed_recall", "typed_f1", "det_f1", "deadline_acc", "unsupported_field_rate", "schema_valid", "latency_mean_s", "latency_p95_s"]))
L.append(block("Model A - action classifier", csv("model_a_comparison")))
L.append(block("Model B / Experiment 2 - follow-up risk", csv("model_b_comparison"), ["model", "features", "val_pr_auc", "test_pr_auc", "test_pr_auc_ci_lo", "test_pr_auc_ci_hi", "test_roc_auc", "test_brier", "test_ece", "test_ece_uncalibrated", "orig_protocol_test_pr_auc"]))
L.append(block("Model B baselines", csv("model_b_baselines"), ["model", "n", "prevalence", "pr_auc", "roc_auc", "brier", "ece"]))
L.append(block("Model C - appointment no-show (real data)", csv("model_c_comparison")))
L.append(block("Model C - subgroup screen", csv("model_c_subgroups")))
L.append(block("Experiment 3 - systems (threshold-free)", csv("exp3_summary")))
ew = csv("exp3_early_warning")
if ew is not None:
    L.append(block("Experiment 3 - early warning at validation-chosen thresholds (recall target 0.7)", ew[ew["target_recall(val)"] == 0.7], ["system", "min_lead_h", "threshold(val)", "alerts", "recall", "precision", "false_alert_rate", "median_lead_h", "alerts_on_unverified_or_censored"]))
L.append(block("Experiment 3 - alerts by rule (system C engine)", csv("exp3_alerts_by_rule")))
L.append(block("Experiment 4 - evidence uncertainty", csv("exp4_evidence_uncertainty")))
L.append(block("Experiment 5 - feature ablations (dense test)", csv("exp5_feature_ablation_dense_test")))
L.append(block("Experiment 5 - ablation summary", csv("exp5_ablation_summary")))
L.append(block("Experiment 5 - GenAI extraction end to end", csv("exp5_genai_end_to_end_primary")))
L.append(block("Section 11 - priority methods", csv("priority_methods")))
L.append(block("Error rates by hidden generator profile (post-hoc analysis only)", csv("error_by_profile")))
bj = R / "benchmarks.json"
if bj.exists():
    b = json.loads(bj.read_text())
    L.append(block("Benchmarks - ML latency", pd.DataFrame(b["ml_latency"])))
    L.append(block("Benchmarks - ML concurrency", pd.DataFrame(b["ml_concurrency"])))
    L.append(block("Benchmarks - event throughput (the peak_rss_mb column is dropped: in the archived runs it was the notebook kernel's lifetime peak inherited by the worker, see README)", pd.DataFrame(b["throughput"]).drop(columns=["peak_rss_mb"], errors="ignore")))
    pmf = R / "benchmark_peak_memory.csv"
    if pmf.exists():
        L.append(block("Benchmarks - per-workload peak memory (VmHWM of a fresh process; scripts/bench_peak_memory.py)", pd.read_csv(pmf)))
    L.append(block("Benchmarks - queue / backlog / loss", pd.DataFrame(b["queue"])))
    L.append(block("Benchmarks - LLM concurrency", pd.DataFrame(b["llm_concurrency"])))
    L.append("### Benchmarks - LLM generation\n\n```\n" + json.dumps({k: v for k, v in b["llm"].items()}, indent=1, default=str)[:1500] + "\n```\n\n")
    if b["nnpa_matmul"].get("available"):
        L.append(block("Benchmarks - NNPA (zDNN) matmul vs CPU", pd.DataFrame(b["nnpa_matmul"]["rows"])[["M", "K", "N", "nnpa_op_ms", "nnpa_total_ms", "numpy_blas_ms", "cpu_naive_c_ms", "speedup_op_vs_numpy", "speedup_total_vs_numpy", "max_abs_err", "max_abs_ref"]], note=b["nnpa_matmul"]["interpretation"]))
(out / "final_report.md").write_text("\n".join(L))
print("wrote reports/final_report.md", sum(len(x) for x in L), "chars")
